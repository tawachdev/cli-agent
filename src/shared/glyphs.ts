export interface GlyphWord {
  rows: string[];
  cells: string[][];
  width: number;
}

const WIDE_GAP = "  ";
const MINI_GAP = " ";

export function glyphWord(word: string, mini: boolean): GlyphWord | null {
  const font = mini ? MINI_GLYPHS : WIDE_GLYPHS;
  const letters = word.toUpperCase().split("");
  if (letters.length === 0 || letters.some((letter) => !font[letter])) return null;
  const gap = mini ? MINI_GAP : WIDE_GAP;
  const rowCount = mini ? 4 : 6;
  const cells: string[][] = [];
  for (let r = 0; r < rowCount; r++) {
    cells.push(letters.map((letter) => font[letter]![r]!));
  }
  const rows = cells.map((rowCells) => rowCells.join(gap));
  return { rows, cells, width: rows[0]!.length };
}
